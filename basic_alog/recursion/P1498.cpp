#include<iostream>
#include<cstring>
using namespace std;
int n;
char a[3000][3000];
int h=2,w=4;
int main(){
	cin>>n;

    //initialize
	memset(a,' ',sizeof(a));
    a[0][0] = a[0][3] = ' ';
    a[0][1] = a[1][0] = '/';
    a[0][2] = a[1][3] = '\\';
    a[1][1] = a[1][2] = '_';

    //fill
    while(n-- > 1){
        for(int i = 0; i < h; ++i){
            for(int j = 0; j < w; ++j){
                a[i+h][j] = a[i+h][j+w] = a[i][j];
                a[i][j] = ' ';
            }            
        }

        for(int i = h; i < 2*h; ++i){
            for(int j = 0; j < w; ++j){
                a[i-h][j+h] = a[i][j];  // h == w/2
            }
        }

        //update
        w *= 2;
        h *= 2;
    }

    for(int i = 0; i < h; ++i){
        for(int j = 0; j < w; ++j){
            cout << a[i][j];
            if(j+1 == w)    cout << '\n';
        }
    }
	return 0;
}

